const languageNames = ["ru", "kz", "en"];
const savedLanguage = localStorage.getItem("unobtainium-language") || "ru";

function addLanguageSwitcher() {
  const header = document.querySelector(".header");
  if (!header || header.querySelector(".language-switcher")) return;

  const switcher = document.createElement("div");
  switcher.className = "language-switcher";

  languageNames.forEach(lang => {
    const button = document.createElement("button");
    button.type = "button";
    button.textContent = lang.toUpperCase();
    button.className = "lang-btn";
    button.dataset.lang = lang;

    button.addEventListener("click", () => {
      localStorage.setItem("unobtainium-language", lang);
      applyLanguage(lang);
    });

    switcher.appendChild(button);
  });

  const menuButton = header.querySelector(".menu-toggle");
  if (menuButton) {
    menuButton.before(switcher);
  } else {
    header.appendChild(switcher);
  }
}

function applyLanguage(lang) {
  if (!languageNames.includes(lang)) lang = "ru";

  document.documentElement.lang = lang;

  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT
  );

  let node;
  while ((node = walker.nextNode())) {
    if (!node.__originalText) {
      node.__originalText = node.nodeValue;
    }

    const original = node.__originalText;
    const trimmed = original.trim();

    if (!trimmed) continue;

    const translation = translations[trimmed];

    if (translation) {
      const translated = lang === "ru"
        ? trimmed
        : translation[lang === "kz" ? 0 : 1];

      node.nodeValue = original.replace(trimmed, translated);
    }
  }

  document.querySelectorAll(".lang-btn").forEach(button => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  const menuButton = document.querySelector(".menu-toggle");
  if (menuButton) {
    menuButton.setAttribute(
      "aria-label",
      lang === "kz" ? "Мәзірді ашу" :
      lang === "en" ? "Open menu" : "Открыть меню"
    );
  }

  const titleTranslations = {
    "Главная": ["Басты бет", "Home"],
    "О компании": ["Компания туралы", "About us"],
    "Услуги": ["Қызметтер", "Services"],
    "Обучение": ["Оқыту", "Training"],
    "Документы": ["Құжаттар", "Documents"],
    "Контакты": ["Байланыс", "Contacts"]
  };

  const titleMatch = document.title.match(/^(.*?) — UNOBTAINIUM$/);
  if (titleMatch && titleTranslations[titleMatch[1]]) {
    const name = titleTranslations[titleMatch[1]];
    document.title = (lang === "ru" ? titleMatch[1] :
      name[lang === "kz" ? 0 : 1]) + " — UNOBTAINIUM";
  }
}

const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".nav");

if (menuButton && navigation) {
  menuButton.addEventListener("click", () => {
    navigation.classList.toggle("open");
  });
}

document.querySelectorAll(".year").forEach(element => {
  element.textContent = new Date().getFullYear();
});

addLanguageSwitcher();
applyLanguage(savedLanguage);
