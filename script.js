const LANGS = ["ru", "kz", "en"];
const HTML_LANG = { ru: "ru", kz: "kk", en: "en" };
let currentLang = "ru";

function rememberRussian() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    if (el.dataset.ru === undefined) el.dataset.ru = el.textContent;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    if (el.dataset.ruPh === undefined) el.dataset.ruPh = el.getAttribute("placeholder") || "";
  });
}

function tr(key, lang = currentLang) {
  if (lang !== "ru" && I18N[lang] && I18N[lang][key]) return I18N[lang][key];
  if (I18N.ru_labels[key]) return I18N.ru_labels[key];
  const el = document.querySelector(`[data-i18n="${key}"]`);
  return el ? el.dataset.ru : key;
}

function setLanguage(lang) {
  if (!LANGS.includes(lang)) lang = "ru";
  currentLang = lang;
  try { localStorage.setItem("siteLanguage", lang); } catch (e) { /* приватный режим */ }
  document.documentElement.lang = HTML_LANG[lang];

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const text = lang === "ru" ? el.dataset.ru : (I18N[lang][key] || el.dataset.ru);
    if (el.tagName === "TITLE") document.title = text;
    else el.textContent = text;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.dataset.i18nPh;
    el.setAttribute("placeholder", lang === "ru" ? el.dataset.ruPh : (I18N[lang][key] || el.dataset.ruPh));
  });
  document.querySelectorAll(".lang-btn").forEach(btn => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle("active", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });
}

function initMenu() {
  const header = document.querySelector(".header");
  const burger = document.querySelector(".burger");
  if (!header || !burger) return;
  const close = () => { header.classList.remove("nav-open"); burger.setAttribute("aria-expanded", "false"); };
  burger.addEventListener("click", () => {
    const open = header.classList.toggle("nav-open");
    burger.setAttribute("aria-expanded", open ? "true" : "false");
  });
  document.querySelectorAll(".nav a").forEach(a => a.addEventListener("click", close));
  document.addEventListener("keydown", e => { if (e.key === "Escape") close(); });
}

function initForm() {
  const form = document.getElementById("request-form");
  if (!form) return;
  const f = n => form.elements.namedItem(n);
  const service = new URLSearchParams(location.search).get("service");
  if (service && f("service").querySelector(`option[value="${service}"]`)) f("service").value = service;

  form.addEventListener("submit", e => {
    e.preventDefault();
    const error = form.querySelector(".form-error");
    const name = f("name").value.trim(), phone = f("phone").value.trim();
    if (!name || phone.replace(/\D/g, "").length < 10) {
      error.hidden = false;
      (name ? f("phone") : f("name")).focus();
      return;
    }
    error.hidden = true;
    const option = f("service").options[f("service").selectedIndex];
    const lines = [
      tr("f_msg_head"),
      `${tr("f_name")}: ${name}`,
      `${tr("f_phone")}: ${phone}`,
    ];
    if (f("company").value.trim()) lines.push(`${tr("f_company").replace(/\s*\(.*\)$/, "")}: ${f("company").value.trim()}`);
    lines.push(`${tr("f_service")}: ${option.textContent.trim()}`);
    if (f("comment").value.trim()) lines.push(`${tr("f_comment")}: ${f("comment").value.trim()}`);
    const url = `${form.dataset.wa}?text=${encodeURIComponent(lines.join("\n"))}`;
    window.open(url, "_blank", "noopener");
  });
}

document.addEventListener("DOMContentLoaded", () => {
  rememberRussian();
  let saved = "ru";
  try { saved = localStorage.getItem("siteLanguage") || "ru"; } catch (e) { /* приватный режим */ }
  setLanguage(saved);
  document.querySelectorAll(".lang-btn").forEach(btn => btn.addEventListener("click", () => setLanguage(btn.dataset.lang)));
  initMenu();
  initForm();
  const year = document.getElementById("year");
  if (year) year.textContent = new Date().getFullYear();
});
