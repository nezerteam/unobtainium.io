const LANGS = ["ru", "kz", "en"];
const HTML_LANG = { ru: "ru", kz: "kk", en: "en" };
let currentLang = "ru";

function rememberRussian() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    if (el.dataset.ru === undefined) el.dataset.ru = el.textContent;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    if (el.dataset.ruPh === undefined) el.dataset.ruPh = el.getAttribute("placeholder") || "";
  });
}

function tr(key, lang = currentLang) {
  if (lang !== "ru" && I18N[lang] && I18N[lang][key]) return I18N[lang][key];
  if (I18N.ru_labels[key]) return I18N.ru_labels[key];
  const el = document.querySelector(`[data-i18n="${key}"]`);
  return el ? el.dataset.ru : key;
}

