function setLanguage(lang) {
  if (!translations[lang]) {
    lang = "ru";
  }

  localStorage.setItem("siteLanguage", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");

    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    const key = element.getAttribute("data-i18n-title");

    if (translations[lang][key]) {
      element.title = translations[lang][key];
    }
  });

  document.querySelectorAll(".eyebrow").forEach(element => {
    const originalText = element.dataset.originalText ||
      element.textContent.trim();

    element.dataset.originalText = originalText;

    if (eyebrowTranslations[originalText]) {
      element.textContent = eyebrowTranslations[originalText][lang];
    }
  });

  document.querySelectorAll(".section-heading").forEach(element => {
    const originalText = element.dataset.originalText ||
      element.textContent.trim();

    element.dataset.originalText = originalText;

    if (staticTextTranslations[originalText]) {
      element.textContent = staticTextTranslations[originalText][lang];
    }
  });

  const currentPage = window.location.pathname.split("/").pop() || "index.html";

  if (pageTitles[currentPage]) {
    document.title = pageTitles[currentPage][lang];
  }

  document.querySelectorAll(".lang-btn").forEach(button => {
    button.classList.toggle(
      "active",
      button.getAttribute("data-lang") === lang
    );
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLanguage = localStorage.getItem("siteLanguage") || "ru";

  setLanguage(savedLanguage);

  document.querySelectorAll(".lang-btn").forEach(button => {
    button.addEventListener("click", () => {
      setLanguage(button.getAttribute("data-lang"));
    });
  });

  const yearElement = document.getElementById("year");

  if (yearElement) {
    yearElement.textContent = new Date().getFullYear();
  }
});
